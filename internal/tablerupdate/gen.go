// identifier mirrors fyne_iconkit's iconconst naming ("arrow-up" → "IconArrowUp").
func identifier(name string) (string, error) {
	segments := strings.FieldsFunc(name, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
	if len(segments) == 0 {
		return "", fmt.Errorf("icon name %q has no usable characters", name)
	}
	ident := "Icon"
	for _, s := range segments {
		ident += strings.ToUpper(s[:1]) + s[1:]
	}
	if !token.IsIdentifier(ident) {
		return "", fmt.Errorf("icon name %q does not yield an identifier (%s)", name, ident)
	}
	return ident, nil
}

func mustIdentifier(name string) string {
	ident, err := identifier(name)
	if err != nil {
		return name
	}
	return ident
}

// generateAliases returns the Go file declaring TablerVersion, the deprecated
// alias variables and the alias map used by Lookup. names are the current icons.
func generateAliases(pkg string, st *state, names map[string]bool) ([]byte, error) {
	idents := map[string]string{}
	for name := range names {
		ident, err := identifier(name)
		if err != nil {
			return nil, err
		}
		idents[ident] = name
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by tablerupdate from tabler.json; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkg)
	fmt.Fprintf(&buf, "// TablerVersion is the release of Tabler Icons embedded in this package.\n")
	fmt.Fprintf(&buf, "const TablerVersion = %q\n\n", st.Version)
	fmt.Fprintf(&buf, "// Deprecated aliases of %d renamed icons. Like Tabler, each alias is kept\n", len(st.Aliases))
	fmt.Fprintf(&buf, "// until the next major release of Tabler Icons.\n")
	buf.WriteString("var (\n")
	for _, a := range st.Aliases {
		switch {
		case names[a.Name]:
			return nil, fmt.Errorf("alias %q is an icon name", a.Name)
		case !names[a.Target]:
			return nil, fmt.Errorf("alias %q: target %q does not exist", a.Name, a.Target)
		}
		ident, err := identifier(a.Name)
		if err != nil {
			return nil, err
		}
		if other, dup := idents[ident]; dup {
			return nil, fmt.Errorf("alias %q and %q both map to identifier %s", a.Name, other, ident)
		}
		idents[ident] = a.Name
		target := mustIdentifier(a.Target)

		fmt.Fprintf(&buf, "\t// %s is the former name of %s.\n\t//\n", ident, target)
		fmt.Fprintf(&buf, "\t// Deprecated: Tabler Icons %s renamed %q to %q, use %s. The alias is removed with Tabler Icons %d.\n", a.Since, a.Name, a.Target, target, major(a.Since)+1)
		fmt.Fprintf(&buf, "\t%s = %s\n", ident, target)
	}
	buf.WriteString(")\n\n")

	buf.WriteString("// aliases maps deprecated icon names to their current names.\n")
	buf.WriteString("var aliases = map[string]string{\n")
	for _, a := range st.Aliases {
		fmt.Fprintf(&buf, "\t%q: %q,\n", a.Name, a.Target)
	}
	buf.WriteString("}\n")
	return format.Source(buf.Bytes())
}

// notes is the changelog entry of one imported release.
type notes struct {
	From, To   string
	Total      int
	Diff       iconDiff
	Aliased    []alias
	Retargeted []aliasChange
	Dropped    []aliasChange
}

// maxNotes keeps release notes below GitHub's limit for pull request bodies.
const maxNotes = 60000

// markdown renders the notes. Without lists, added and changed icons are
// only counted.
func (n *notes) markdown(lists bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## Tabler Icons %s\n\n", n.To)
	fmt.Fprintf(&b, "Updated from [%s to %s](https://github.com/tabler/tabler-icons/compare/v%s...v%s), %d icons in total.\n\n",
		n.From, n.To, n.From, n.To, n.Total)

	renamed := map[string]bool{}
	for _, a := range n.Aliased {
		renamed[a.Name] = true
		renamed[a.Target] = true
	}
	var removed, added []string
	for _, name := range n.Diff.Removed {
		if !renamed[name] {
			removed = append(removed, name)
		}
	}
	for _, name := range n.Diff.Added {
		if !renamed[name] {
			added = append(added, name)
		}
	}

	breaking := len(removed) + len(n.Dropped)
	if breaking > 0 {
		fmt.Fprintf(&b, "> [!WARNING]\n> Breaking: %d `Icon*` variables are removed, see below.\n\n", breaking)
	}

	if len(n.Aliased) > 0 {
		fmt.Fprintf(&b, "### Renamed (%d)\n\n", len(n.Aliased))
		fmt.Fprintf(&b, "The old names stay available as deprecated aliases until Tabler Icons %d; `Lookup` resolves them too. "+
			"Icons marked ⚠️ look different under the new name.\n\n", major(n.To)+1)
		b.WriteString("| Old name | New name | Go | Detected by |\n|---|---|---|---|\n")
		for _, a := range n.Aliased {
			mark := ""
			if n.Diff.Renames[a.Name].ShapeChanged {
				mark = " ⚠️"
			}
			fmt.Fprintf(&b, "| `%s` | `%s`%s | `%s` → `%s` | %s |\n", a.Name, a.Target, mark, mustIdentifier(a.Name), mustIdentifier(a.Target), sourceText(a.Source))
		}
		b.WriteString("\n")
	}
	if len(removed) > 0 {
		fmt.Fprintf(&b, "### Removed (%d)\n\n", len(removed))
		b.WriteString("No successor was found. If there is one, add it to `aliases` in `tabler.json` (source `manual`) and run `go run ./internal/tablerupdate -offline`.\n\n")
		for _, name := range removed {
			fmt.Fprintf(&b, "- `%s` (`%s`)\n", name, mustIdentifier(name))
		}
		b.WriteString("\n")
	}
	if len(n.Dropped) > 0 {
		fmt.Fprintf(&b, "### Removed deprecated aliases (%d)\n\n", len(n.Dropped))
		for _, a := range n.Dropped {
			fmt.Fprintf(&b, "- `%s` (`%s`), use `%s`: %s\n", a.Name, mustIdentifier(a.Name), mustIdentifier(a.Target), a.Note)
		}
		b.WriteString("\n")
	}
	if len(n.Retargeted) > 0 {
		fmt.Fprintf(&b, "### Updated aliases (%d)\n\n", len(n.Retargeted))
		for _, a := range n.Retargeted {
			fmt.Fprintf(&b, "- `%s`: %s\n", a.Name, a.Note)
		}
		b.WriteString("\n")
	}
	writeList(&b, "Added", added, lists)
	writeList(&b, "Changed shape", n.Diff.Changed, lists)
	return b.String()
}

func sourceText(source string) string {
	switch source {
	case sourceTabler:
		return "Tabler aliases"
	case sourceName:
		return "name"
	case sourceShape:
		return "identical shape"
	case sourceManual:
		return "manual"
	}
	return source
}

func writeList(b *strings.Builder, title string, names []string, list bool) {
	if len(names) == 0 {
		return
	}
	if !list {
		fmt.Fprintf(b, "### %s (%d)\n\nSee CHANGELOG.md for the list.\n\n", title, len(names))
		return
	}
	fmt.Fprintf(b, "### %s (%d)\n\n<details>\n<summary>Show icons</summary>\n\n", title, len(names))
	for _, name := range names {
		fmt.Fprintf(b, "- `%s` (`%s`)\n", name, mustIdentifier(name))
	}
	b.WriteString("\n</details>\n\n")
}

const changelogHeader = "# Changelog\n\n"

// prependChangelog inserts entry as the newest section of the changelog.
func prependChangelog(file, entry string) error {
	src, err := os.ReadFile(file)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	rest := strings.TrimPrefix(string(src), changelogHeader)
	out := changelogHeader + strings.TrimRight(entry, "\n") + "\n"
	if rest = strings.TrimSpace(rest); rest != "" {
		out += "\n" + rest + "\n"
	}
	return os.WriteFile(file, []byte(out), 0o644)
}

var readmeVersion = regexp.MustCompile(`(\[Tabler Icons\]\(https://tabler\.io/icons\) \()v([0-9][0-9A-Za-z.+-]*)(\))`)

func readmeVersionOf(file string) (string, error) {
	src, err := os.ReadFile(file)
	if err != nil {
		return "", err
	}
	m := readmeVersion.FindSubmatch(src)
	if m == nil {
		return "", fmt.Errorf("%s: no %q found", file, "[Tabler Icons](https://tabler.io/icons) (vX.Y.Z)")
	}
	return string(m[2]), nil
}

func updateReadme(file, version string) error {
	src, err := os.ReadFile(file)
	if err != nil {
		return err
	}
	if !readmeVersion.Match(src) {
		return fmt.Errorf("%s: no %q found", file, "[Tabler Icons](https://tabler.io/icons) (vX.Y.Z)")
	}
	out := readmeVersion.ReplaceAll(src, []byte("${1}v"+version+"${3}"))
	if bytes.Equal(src, out) {
		return nil
	}
	return os.WriteFile(file, out, 0o644)
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
